@dataclass(frozen=True, slots=True)
class ParameterSpec:
    """Неизменяемая часть параметра профиля."""

    id: str
    block: str
    title: str
    klass: str
    target: str | None
    unit: str | None
    projection: tuple[str, ...]
    kind: str
    default: Any
    source: str

    @property
    def needs_projection(self) -> bool:
        """Параметр обязан попасть в целевой вектор (классы С и Э)."""
        return self.klass in {"C", "E"}


def _p(
    pid: str,
    block: str,
    title: str,
    klass: str,
    target: str | None,
    unit: str | None,
    projection: tuple[str, ...],
    kind: str,
    default: Any,
    source: str,
) -> ParameterSpec:
    return ParameterSpec(pid, block, title, klass, target, unit, projection, kind, default, source)


